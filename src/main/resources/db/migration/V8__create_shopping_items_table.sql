CREATE TABLE shopping_items (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        quantity NUMERIC(12, 3) NOT NULL DEFAULT 1,
        unit VARCHAR(20) NOT NULL,
        checked BOOLEAN NOT NULL DEFAULT FALSE,
        checked_at TIMESTAMP,
        shopping_list_id BIGINT NOT NULL,
        product_id BIGINT NOT NULL,
        created_at TIMESTAMP NOT NULL,
        updated_at TIMESTAMP NOT NULL,

        CONSTRAINT fk_shopping_items_list FOREIGN KEY (shopping_list_id) REFERENCES shopping_lists(id) ON DELETE CASCADE,

        CONSTRAINT fk_shopping_items_product FOREIGN KEY (product_id) REFERENCES products(id),

        CONSTRAINT uk_shopping_items_list_product UNIQUE (shopping_list_id, product_id),

        CONSTRAINT chk_shopping_items_quantity CHECK (quantity > 0),

        CONSTRAINT chk_shopping_items_unit CHECK (unit IN ('UNIT', 'KG', 'G', 'L', 'ML', 'PACKAGE', 'BOX'))
);

CREATE INDEX idx_shopping_items_list_id ON shopping_items(shopping_list_id);

CREATE INDEX idx_shopping_items_product_id ON shopping_items(product_id);