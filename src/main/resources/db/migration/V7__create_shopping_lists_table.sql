CREATE TABLE shopping_lists (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name VARCHAR(150) NOT NULL,
        status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
        user_id BIGINT NOT NULL,
        created_at TIMESTAMP NOT NULL,
        updated_at TIMESTAMP NOT NULL,
        completed_at TIMESTAMP,

        CONSTRAINT fk_shopping_lists_user FOREIGN KEY (user_id) REFERENCES users(id),
        CONSTRAINT chk_shopping_lists_status CHECK (status IN ('ACTIVE', 'COMPLETED'))
);

CREATE INDEX idx_shopping_lists_user_status_created ON shopping_lists (user_id, status, created_at DESC);